"""HANA graph adapter (spec §1.12). Own connection pool (graph pool, no SET SCHEMA; statements are
schema-qualified). OpenCypher is tried for hierarchy expansion, with a SQL fallback. Not exercised by tests.
"""
from __future__ import annotations

import hashlib
import json
import logging
import re
import threading
from typing import Iterable, Sequence

from app import config

log = logging.getLogger(__name__)
_CHUNK = 1000
_pool = None
_pool_lock = threading.Lock()


def graph_pool():
    global _pool
    if _pool is None:
        with _pool_lock:
            if _pool is None:
                from app.hana_conn import _Pool

                _pool = _Pool(size=max(1, config.HANA_POOL_SIZE), timeout=config.HANA_GRAPH_POOL_TIMEOUT,
                              overflow=config.HANA_MAX_OVERFLOW, recycle=config.HANA_POOL_RECYCLE,
                              set_schema=False)
    return _pool


def project_prefix(pid: str) -> str:
    """`KH_` for the orchestrator, else `KH_P_<SLUG>_<HASH6>_`."""
    if pid == config.ORCHESTRATOR_ID:
        return config.GRAPH_TABLE_PREFIX
    slug = re.sub("[^A-Z0-9]+", "_", pid.upper()).strip("_")[:40]
    h = hashlib.sha1(pid.encode("utf-8")).hexdigest()[:6].upper()
    return f"KH_P_{slug}_{h}_"


def _attrs(v) -> str:
    return v if isinstance(v, str) else json.dumps(v or {}, ensure_ascii=False)


def _parse(v):
    if not v:
        return {}
    try:
        return json.loads(v)
    except (ValueError, TypeError):
        return v


class HanaAdapter:
    backend = "hana"

    def __init__(self, prefix: str | None = None, workspace: str | None = None):
        self.prefix = prefix or config.GRAPH_TABLE_PREFIX
        self.schema = config.HANA_SCHEMA
        q = f'"{self.schema}".'
        self.T_DOC = f"{q}{self.prefix}DOCUMENTS"
        self.T_NODE = f"{q}{self.prefix}GRAPH_NODES"
        self.T_EDGE = f"{q}{self.prefix}GRAPH_EDGES"
        self.workspace = workspace or (config.HANA_GRAPH_WORKSPACE if self.prefix == config.GRAPH_TABLE_PREFIX
                                       else f"{self.prefix}GRAPH_WS")

    # -- plumbing ---------------------------------------------------------
    def _run(self, fn):
        pool = graph_pool()
        conn = pool.acquire()
        try:
            cur = conn.cursor()
            try:
                out = fn(cur)
            finally:
                cur.close()
            conn.commit()
            return out
        except Exception:
            try:
                conn.rollback()
            except Exception:
                pass
            raise
        finally:
            pool.release(conn)

    def probe(self) -> bool:
        pool = graph_pool()
        conn = pool.acquire()
        pool.release(conn)
        return True

    def _table_exists(self, cur, name: str) -> bool:
        cur.execute("SELECT COUNT(*) FROM SYS.TABLES WHERE SCHEMA_NAME=? AND TABLE_NAME=?", (self.schema, name))
        return bool(cur.fetchone()[0])

    def bootstrap(self) -> None:
        p = self.prefix

        def run(cur):
            cur.execute("SELECT COUNT(*) FROM SYS.SCHEMAS WHERE SCHEMA_NAME=?", (self.schema,))
            if not cur.fetchone()[0]:
                cur.execute(f'CREATE SCHEMA "{self.schema}"')
            if not self._table_exists(cur, f"{p}DOCUMENTS"):
                cur.execute(f"CREATE COLUMN TABLE {self.T_DOC} (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                            f"CHECKSUM NVARCHAR(64) UNIQUE, SOURCE_TEXT NCLOB, CREATED_AT TIMESTAMP)")
            if not self._table_exists(cur, f"{p}GRAPH_NODES"):
                cur.execute(f"CREATE COLUMN TABLE {self.T_NODE} (CORE_ID NVARCHAR(500) PRIMARY KEY, "
                            f"ENTITY_TYPE NVARCHAR(100), LABEL NVARCHAR(500), ATTRIBUTES NCLOB, DOCUMENT_ID BIGINT, "
                            f"SOURCE_TEXT NCLOB, CREATED_AT TIMESTAMP, UPDATED_AT TIMESTAMP)")
            if not self._table_exists(cur, f"{p}GRAPH_EDGES"):
                cur.execute(f"CREATE COLUMN TABLE {self.T_EDGE} (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                            f"SOURCE_CORE_ID NVARCHAR(500), RELATION NVARCHAR(200), TARGET_CORE_ID NVARCHAR(500), "
                            f"CREATED_AT TIMESTAMP, ATTRIBUTES NCLOB, SOURCE_TEXT NCLOB, CONFIDENCE DOUBLE, "
                            f"UNIQUE (SOURCE_CORE_ID, RELATION, TARGET_CORE_ID))")
            for col, typ in (("ATTRIBUTES", "NCLOB"), ("SOURCE_TEXT", "NCLOB"), ("CONFIDENCE", "DOUBLE")):
                cur.execute("SELECT COUNT(*) FROM SYS.TABLE_COLUMNS WHERE SCHEMA_NAME=? AND TABLE_NAME=? "
                            "AND COLUMN_NAME=?", (self.schema, f"{p}GRAPH_EDGES", col))
                if not cur.fetchone()[0]:
                    cur.execute(f"ALTER TABLE {self.T_EDGE} ADD ({col} {typ})")
            try:
                cur.execute("SELECT COUNT(*) FROM SYS.GRAPH_WORKSPACES WHERE SCHEMA_NAME=? AND WORKSPACE_NAME=?",
                            (self.schema, self.workspace))
                if not cur.fetchone()[0]:
                    cur.execute(
                        f'CREATE GRAPH WORKSPACE "{self.schema}"."{self.workspace}" '
                        f"EDGE TABLE {self.T_EDGE} SOURCE COLUMN SOURCE_CORE_ID TARGET COLUMN TARGET_CORE_ID "
                        f"KEY COLUMN ID VERTEX TABLE {self.T_NODE} KEY COLUMN CORE_ID")
            except Exception as e:  # noqa: BLE001
                log.warning("graph workspace %s not created: %s", self.workspace, e)

        self._run(run)

    def drop(self) -> bool:
        if self.prefix == config.GRAPH_TABLE_PREFIX:
            raise ValueError("refusing to drop the orchestrator graph")

        def run(cur):
            try:
                cur.execute(f'DROP GRAPH WORKSPACE "{self.schema}"."{self.workspace}"')
            except Exception:
                pass
            for t in (self.T_EDGE, self.T_NODE, self.T_DOC):
                try:
                    cur.execute(f"DROP TABLE {t}")
                except Exception:
                    pass
            return True

        return self._run(run)

    # -- writes -----------------------------------------------------------
    def _document_id(self, cur, text):
        if not text:
            return None
        chk = hashlib.sha256(text.encode("utf-8")).hexdigest()
        cur.execute(f"SELECT ID FROM {self.T_DOC} WHERE CHECKSUM=?", (chk,))
        r = cur.fetchone()
        if r:
            return int(r[0])
        cur.execute(f"INSERT INTO {self.T_DOC} (CHECKSUM, SOURCE_TEXT, CREATED_AT) VALUES (?, ?, CURRENT_UTCTIMESTAMP)",
                    (chk, text))
        cur.execute(f"SELECT ID FROM {self.T_DOC} WHERE CHECKSUM=?", (chk,))
        return int(cur.fetchone()[0])

    def upsert_nodes(self, nodes: Iterable[dict]) -> int:
        nodes = list(nodes)

        def run(cur):
            for nd in nodes:
                st = nd.get("source_text") or ""
                doc = self._document_id(cur, st)
                cur.execute(
                    f"MERGE INTO {self.T_NODE} T USING (SELECT ? AS CORE_ID FROM DUMMY) S ON T.CORE_ID = S.CORE_ID "
                    f"WHEN MATCHED THEN UPDATE SET T.ENTITY_TYPE=?, T.LABEL=?, T.ATTRIBUTES=?, T.DOCUMENT_ID=?, "
                    f"T.SOURCE_TEXT=?, T.UPDATED_AT=CURRENT_UTCTIMESTAMP "
                    f"WHEN NOT MATCHED THEN INSERT (CORE_ID, ENTITY_TYPE, LABEL, ATTRIBUTES, DOCUMENT_ID, SOURCE_TEXT, "
                    f"CREATED_AT, UPDATED_AT) VALUES (?, ?, ?, ?, ?, ?, CURRENT_UTCTIMESTAMP, CURRENT_UTCTIMESTAMP)",
                    (nd["core_id"], nd.get("type"), nd.get("label"), _attrs(nd.get("attributes")), doc, st,
                     nd["core_id"], nd.get("type"), nd.get("label"), _attrs(nd.get("attributes")), doc, st))
            return len(nodes)

        return self._run(run)

    def upsert_edges(self, edges: Iterable[dict]) -> int:
        edges = list(edges)

        def run(cur):
            for e in edges:
                conf = 1.0 if e.get("confidence") is None else float(e["confidence"])
                cur.execute(
                    f"MERGE INTO {self.T_EDGE} T USING (SELECT ? AS S, ? AS R, ? AS G FROM DUMMY) X "
                    f"ON T.SOURCE_CORE_ID = X.S AND T.RELATION = X.R AND T.TARGET_CORE_ID = X.G "
                    f"WHEN MATCHED THEN UPDATE SET T.ATTRIBUTES=?, T.SOURCE_TEXT=?, T.CONFIDENCE=? "
                    f"WHEN NOT MATCHED THEN INSERT (SOURCE_CORE_ID, RELATION, TARGET_CORE_ID, CREATED_AT, ATTRIBUTES, "
                    f"SOURCE_TEXT, CONFIDENCE) VALUES (?, ?, ?, CURRENT_UTCTIMESTAMP, ?, ?, ?)",
                    (e["source_core_id"], e["relation"], e["target_core_id"], _attrs(e.get("attributes")),
                     e.get("source_text") or "", conf, e["source_core_id"], e["relation"], e["target_core_id"],
                     _attrs(e.get("attributes")), e.get("source_text") or "", conf))
            return len(edges)

        return self._run(run)

    # -- reads ------------------------------------------------------------
    @staticmethod
    def _in(ids) -> str:
        return ", ".join("?" for _ in ids)

    def fetch_graph(self, core_ids: Sequence[str], hierarchy_edges: Sequence[str], hops: int = 3):
        try:
            def run(cur):
                expanded, frontier = set(core_ids), set(core_ids)
                rels = list(hierarchy_edges)
                for _ in range(max(0, int(hops))):
                    if not frontier:
                        break
                    fl = list(frontier)
                    cur.execute(f"SELECT SOURCE_CORE_ID FROM {self.T_EDGE} WHERE TARGET_CORE_ID IN ({self._in(fl)}) "
                                f"AND RELATION IN ({self._in(rels)})", (*fl, *rels))
                    new = {r[0] for r in cur.fetchall()} - expanded
                    expanded |= new
                    frontier = new
                el = list(expanded)
                edges, seen = [], set()
                for i in range(0, len(el), _CHUNK):
                    part = el[i:i + _CHUNK]
                    cur.execute(f"SELECT SOURCE_CORE_ID, RELATION, TARGET_CORE_ID, ATTRIBUTES, SOURCE_TEXT, CONFIDENCE, "
                                f"CREATED_AT FROM {self.T_EDGE} WHERE SOURCE_CORE_ID IN ({self._in(part)}) "
                                f"OR TARGET_CORE_ID IN ({self._in(part)})", (*part, *part))
                    for r in cur.fetchall():
                        k = (r[0], r[1], r[2])
                        if k in seen:
                            continue
                        seen.add(k)
                        edges.append({"source_core_id": r[0], "relation": r[1], "target_core_id": r[2],
                                      "attributes": _parse(_s(r[3])), "source_text": _s(r[4]),
                                      "confidence": r[5], "created_at": str(r[6]) if r[6] else None})
                involved = set(expanded) | {e["source_core_id"] for e in edges} | {e["target_core_id"] for e in edges}
                il = sorted(involved)
                nodes = []
                for i in range(0, len(il), _CHUNK):
                    part = il[i:i + _CHUNK]
                    cur.execute(f"SELECT CORE_ID, ENTITY_TYPE, LABEL, ATTRIBUTES, SOURCE_TEXT, CREATED_AT, UPDATED_AT "
                                f"FROM {self.T_NODE} WHERE CORE_ID IN ({self._in(part)})", tuple(part))
                    for r in cur.fetchall():
                        nodes.append({"core_id": r[0], "entity_type": r[1], "label": r[2],
                                      "attributes": _parse(_s(r[3])), "source_text": _s(r[4]),
                                      "created_at": str(r[5]) if r[5] else None,
                                      "updated_at": str(r[6]) if r[6] else None})
                return nodes, edges

            return self._run(run)
        except Exception as e:  # noqa: BLE001
            log.warning("fetch_graph failed: %s", e)
            return [], []

    def delete_nodes(self, ids: Sequence[str]) -> dict:
        ids = list(ids)

        def run(cur):
            n = m = 0
            for i in range(0, len(ids), _CHUNK):
                part = ids[i:i + _CHUNK]
                cur.execute(f"DELETE FROM {self.T_EDGE} WHERE SOURCE_CORE_ID IN ({self._in(part)}) "
                            f"OR TARGET_CORE_ID IN ({self._in(part)})", (*part, *part))
                m += max(0, cur.rowcount or 0)
                cur.execute(f"DELETE FROM {self.T_NODE} WHERE CORE_ID IN ({self._in(part)})", tuple(part))
                n += max(0, cur.rowcount or 0)
            return {"nodes_deleted": n, "edges_deleted": m}

        return self._run(run)

    def delete_orphan_documents(self) -> int:
        def run(cur):
            cur.execute(f"DELETE FROM {self.T_DOC} WHERE ID NOT IN "
                        f"(SELECT DOCUMENT_ID FROM {self.T_NODE} WHERE DOCUMENT_ID IS NOT NULL)")
            return max(0, cur.rowcount or 0)

        return self._run(run)

    def traverse_logic(self, start_ids, relations=None, max_depth: int = 3) -> list[dict]:
        def run(cur):
            seen_nodes, frontier, out, seen = set(start_ids), set(start_ids), [], set()
            for _ in range(max(0, int(max_depth))):
                if not frontier:
                    break
                fl = list(frontier)
                sql = (f"SELECT SOURCE_CORE_ID, RELATION, TARGET_CORE_ID FROM {self.T_EDGE} "
                       f"WHERE SOURCE_CORE_ID IN ({self._in(fl)})")
                params = list(fl)
                if relations:
                    sql += f" AND RELATION IN ({self._in(relations)})"
                    params += list(relations)
                cur.execute(sql, tuple(params))
                nxt = set()
                for r in cur.fetchall():
                    if (r[0], r[1], r[2]) not in seen:
                        seen.add((r[0], r[1], r[2]))
                        out.append({"source_core_id": r[0], "relation": r[1], "target_core_id": r[2]})
                    if r[2] not in seen_nodes:
                        seen_nodes.add(r[2])
                        nxt.add(r[2])
                frontier = nxt
            return out

        return self._run(run)


def _s(v):
    if v is None or isinstance(v, str):
        return v
    read = getattr(v, "read", None)
    if callable(read):
        d = read()
        return d.decode("utf-8") if isinstance(d, bytes) else d
    return str(v)
