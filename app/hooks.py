MUTATING_TOOLS = {"Write", "Edit", "NotebookEdit", "MultiEdit", "Artifact", "Agent", "Task", "Workflow",
                  "ScheduleWakeup", "PushNotification", "RemoteTrigger", "SendMessage", "EnterWorktree",
                  "ExitWorktree", "DesignSync"}
READONLY_TOOLS = {"Read", "Grep", "Glob", "WebFetch", "WebSearch", "TaskList", "TaskGet", "TaskOutput", "CronList",
                  "ToolSearch", "Skill", "Monitor", "AskUserQuestion", "ReportFindings", "EnterPlanMode",
                  "ExitPlanMode"}
UNKNOWN_IS_MUTATION = True
SHELL_TOOLS = {"Bash", "PowerShell"}
_SHELL_MUTATION = [re.compile(p, re.I) for p in (
    r"/(vector/add|vector/delete|keys/add|keys/delete|layers/add|policy/\S*set|policy/\S*delete|hooks/set|"
    r"hooks/delete|kernel/rules/add|kernel/rules/delete|entities\b|messages\b|feedback/)",
    r"-X\s*(POST|PUT|PATCH|DELETE)\b", r"\bcurl\b[^|]*\s(-d|--data\S*|-F|--form)\b",
    r"(^|[^<>&0-9])>{1,2}\s*[^&\s]", r"\b(rm|rmdir|mv|cp|mkdir|touch|chmod|chown|ln|truncate|dd|tee)\b",
    r"\bsed\s+(-\w*i|--in-place)", r"\b(Set-Content|Add-Content|Out-File|New-Item|Remove-Item|Move-Item|"
    r"Copy-Item|Rename-Item|Clear-Content)\b",
    r"\bgit\s+(add|commit|push|pull|merge|rebase|reset|checkout|switch|stash|tag|cherry-pick|revert|rm|mv|"
    r"clone|init|apply|am)\b",
    r"\b(pip|pip3|npm|yarn|pnpm|apt|apt-get|brew|choco|winget|cargo|gem|conda)\s+(install|uninstall|add|remove|"
    r"update|upgrade|i)\b",
    r"\b\S+\.(py|sh|ps1|bat|cmd)\b", r"\bpython\d?\s+-m\b",
    r"\bdocker(-compose)?\s+(run|up|down|start|stop|rm|build|push|exec|compose)\b",
    r"\b(kill|pkill|taskkill|Stop-Process|Start-Process|systemctl|service)\b",
)]
_TASK_PREFIX = ("Task", "Cron")


def _text_of(content) -> str:
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        out = []
        for p in content:
            if isinstance(p, dict) and p.get("type") == "text":
                out.append(p.get("text") or "")
            elif isinstance(p, str):
                out.append(p)
        return "\n".join(out)
    return ""


def _is_prompt(row: dict) -> bool:
    if row.get("type") != "user" or row.get("toolUseResult") is not None:
        return False
    msg = row.get("message") or {}
    content = msg.get("content") if isinstance(msg, dict) else None
    if isinstance(content, list) and any(isinstance(p, dict) and p.get("type") == "tool_result" for p in content):
        return False
    return bool(_text_of(content).strip())


def _tool_uses(row: dict) -> list[dict]:
    msg = row.get("message") or {}
    content = msg.get("content") if isinstance(msg, dict) else None
    if not isinstance(content, list):
        return []
    return [p for p in content if isinstance(p, dict) and p.get("type") == "tool_use"]


def classify_tool(name: str, inp: dict | None) -> tuple[bool, str]:
    if name in SHELL_TOOLS:
        cmd = str((inp or {}).get("command") or "")
        for rx in _SHELL_MUTATION:
            if rx.search(cmd):
                return True, f"{name}: {cmd[:200]}"
        return False, ""
    if name in MUTATING_TOOLS:
        return True, name
    if name in READONLY_TOOLS:
        return False, ""
    if name.startswith(_TASK_PREFIX):
        return (False, "") if name in READONLY_TOOLS else (True, name)
    return UNKNOWN_IS_MUTATION, f"unknown tool {name}"


def turn_mutated(transcript_path: str, prompt_id: Optional[str] = None) -> dict:
    try:
        with open(transcript_path, encoding="utf-8", errors="replace") as f:
            raw = f.read().splitlines()
    except Exception as e:  # noqa: BLE001
        return {"mutated": True, "reason": f"transcript unreadable: {e}", "tool_count": 0, "how": "fail-safe",
                "evidence": []}
    rows: list = []
    for line in raw:
        if not line.strip():
            continue
        try:
            rows.append(json.loads(line))
        except Exception:  # noqa: BLE001
            rows.append(None)
    start = 0
    for i in range(len(rows) - 1, -1, -1):
        if isinstance(rows[i], dict) and _is_prompt(rows[i]):
            start = i
            break
    how = "last-prompt"
    sl = rows[start:]
    if prompt_id:
        ids = {r.get("promptId") for r in sl if isinstance(r, dict)}
        if prompt_id not in ids:
            sl, how = rows, "whole-transcript"
    evidence: list[str] = []
    tools = 0
    for r in sl:
        if r is None:
            evidence.append("unparseable transcript row")
            continue
        for tu in _tool_uses(r):
            tools += 1
            m, why = classify_tool(str(tu.get("name") or ""), tu.get("input") if isinstance(tu.get("input"), dict)
                                   else {})
            if m:
                evidence.append(why)
    mutated = bool(evidence)
    reason = evidence[0] if evidence else "no mutating tool call in this turn"
    return {"mutated": mutated, "reason": reason, "tool_count": tools, "how": how, "evidence": evidence[:20]}


