"""Hook rule store `hook_rules` (spec §3.5) and its routes; `POST /hooks/turn_mutated` (Stop-hook check).

Served text of a hook type = enabled rules ORDER BY position, id, joined with "\\n\\n", then `{menu}` replaced by
the every-project action menu.
"""
from __future__ import annotations

import json
import logging
import os
import re
from typing import Optional

from fastapi import FastAPI, HTTPException
from fastapi.responses import JSONResponse, PlainTextResponse
from pydantic import BaseModel, Field

from app import sqldb
from app import ctx_util as U

log = logging.getLogger(__name__)

KNOWN_TYPES = ("SessionStart", "UserPromptSubmit", "PreToolUse", "PostToolUse", "Stop", "SubagentStop",
               "Notification", "PreCompact")

_SQLITE = """CREATE TABLE IF NOT EXISTS hook_rules (
    id INTEGER PRIMARY KEY AUTOINCREMENT, hook_type TEXT NOT NULL, name TEXT NOT NULL DEFAULT 'default',
    content TEXT, enabled INTEGER DEFAULT 1, position INTEGER DEFAULT 0, updated_at TEXT,
    UNIQUE(hook_type, name))"""
_HANA = """CREATE COLUMN TABLE hook_rules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, hook_type NVARCHAR(100) NOT NULL,
    name NVARCHAR(200) DEFAULT 'default' NOT NULL, content NCLOB, enabled INTEGER DEFAULT 1,
    position INTEGER DEFAULT 0, updated_at NVARCHAR(40), UNIQUE(hook_type, name))"""
_COLS = ("id", "hook_type", "name", "content", "enabled", "position", "updated_at")
_ready = False


def ensure() -> None:
    global _ready
    if _ready:
        return
    with sqldb.connect() as c:
        sqldb.create_table(c, "hook_rules", _SQLITE, _HANA)
        sqldb.create_index(c, "ix_hook_rules_type", "hook_rules", ["hook_type", "enabled"])
    _ready = True


def _row(r) -> dict:
    d = {k: r[i] for i, k in enumerate(_COLS)}
    d["enabled"] = bool(d["enabled"])
    d["position"] = int(d["position"] or 0)
    return d


def list_rules(hook_type: Optional[str] = None) -> list[dict]:
    ensure()
    sql = f"SELECT {', '.join(_COLS)} FROM hook_rules"
    params: tuple = ()
    if hook_type:
        sql += " WHERE hook_type=?"
        params = (hook_type,)
    sql += " ORDER BY hook_type, position, id"
    with sqldb.connect() as c:
        return [_row(r) for r in c.execute(sql, params).fetchall()]


def enabled_rules(hook_type: str) -> list[dict]:
    rows = [r for r in list_rules(hook_type) if r["enabled"]]
    rows.sort(key=lambda r: (r["position"], r["id"]))
    return rows


def served_text(hook_type: str) -> str:
    from app.policy_actions import lint

    return lint.render("\n\n".join(r["content"] or "" for r in enabled_rules(hook_type)))


def set_rule(hook_type: str, content: str, name: str = "default", enabled: bool = True, position: int = 0) -> dict:
    ensure()
    with sqldb.connect() as c:
        sqldb.upsert(c, "hook_rules", ["hook_type", "name"], {
            "hook_type": hook_type, "name": name or "default", "content": content, "enabled": 1 if enabled else 0,
            "position": int(position), "updated_at": U.now_iso()})
        r = c.execute(f"SELECT {', '.join(_COLS)} FROM hook_rules WHERE hook_type=? AND name=?",
                      (hook_type, name or "default")).fetchone()
    return _row(r)


def insert_if_missing(hook_type: str, name: str, content: str, position: int = 0, enabled: bool = True) -> bool:
    ensure()
    with sqldb.connect() as c:
        return sqldb.insert_new(c, "hook_rules", {
            "hook_type": hook_type, "name": name, "content": content, "enabled": 1 if enabled else 0,
            "position": int(position), "updated_at": U.now_iso()})


def delete_rule(rule_id: Optional[int] = None, hook_type: Optional[str] = None, name: Optional[str] = None) -> int:
    ensure()
    with sqldb.connect() as c:
        if rule_id is not None:
            cur = c.execute("DELETE FROM hook_rules WHERE id=?", (int(rule_id),))
        else:
            cur = c.execute("DELETE FROM hook_rules WHERE hook_type=? AND name=?", (hook_type, name or "default"))
        return max(0, cur.rowcount or 0)


def count() -> int:
    ensure()
    with sqldb.connect() as c:
        return int(c.execute("SELECT COUNT(*) FROM hook_rules").fetchone()[0])


