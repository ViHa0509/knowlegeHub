class HookSet(BaseModel):
    hook_type: str = Field(..., min_length=1, max_length=100)
    content: str
    name: Optional[str] = "default"
    enabled: bool = True
    position: int = 0
    allow_oversize: bool = False
    reason: Optional[str] = None


class HookDelete(BaseModel):
    id: Optional[int] = None
    hook_type: Optional[str] = None
    name: Optional[str] = None


class TurnMutated(BaseModel):
    transcript_path: str
    prompt_id: Optional[str] = None


def attach(app: FastAPI) -> None:
    ensure()

    @app.get("/hooks/get", tags=["hooks"])
    def hooks_get(hook_type: str):
        rules = enabled_rules(hook_type)
        return {"hook_type": hook_type, "count": len(rules), "content": served_text(hook_type), "rules": rules}

    @app.get("/hooks/raw", tags=["hooks"], response_class=PlainTextResponse)
    def hooks_raw(hook_type: str):
        return PlainTextResponse(served_text(hook_type))

    @app.get("/hooks/list", tags=["hooks"])
    def hooks_list(hook_type: Optional[str] = None):
        rules = list_rules(hook_type)
        return {"count": len(rules), "rules": rules, "known_types": list(KNOWN_TYPES)}

    @app.post("/hooks/set", tags=["hooks"])
    def hooks_set(body: HookSet):
        U.need_maintainer()
        name = body.name or "default"
        warnings: list[str] = []
        if body.enabled:
            from app.policy_actions import lint

            errors, warnings = lint.check_hook(body.hook_type, name, body.content)
            refusal = lint.gate(errors, warnings, body.model_dump())
            if refusal is not None:
                return refusal
        row = set_rule(body.hook_type, body.content, name, body.enabled, body.position)
        return {**row, "warnings": warnings}

    @app.post("/hooks/delete", tags=["hooks"])
    def hooks_delete(body: HookDelete):
        U.need_maintainer()
        if body.id is None and not body.hook_type:
            raise HTTPException(status_code=422, detail="send {id} or {hook_type, name}")
        return {"deleted": delete_rule(body.id, body.hook_type, body.name)}

    @app.post("/hooks/turn_mutated", tags=["hooks"])
    def hooks_turn_mutated(body: TurnMutated):
        if not os.path.isfile(body.transcript_path):
            return JSONResponse(content={"mutated": True, "reason": "transcript not found", "tool_count": 0,
                                         "how": "fail-safe", "evidence": []})
        return turn_mutated(body.transcript_path, body.prompt_id)
